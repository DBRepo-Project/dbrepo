package at.tuwien.entities.database.table.columns;

import at.tuwien.entities.container.image.ContainerImageDate;
import at.tuwien.entities.database.View;
import at.tuwien.entities.database.table.Table;
import com.fasterxml.jackson.annotation.JsonFormat;
import lombok.*;
import org.hibernate.annotations.GenericGenerator;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import jakarta.persistence.*;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;

@Data
@Entity
@Builder(toBuilder = true)
@ToString
@AllArgsConstructor
@NoArgsConstructor
@EntityListeners(AuditingEntityListener.class)
@jakarta.persistence.Table(name = "mdb_columns", uniqueConstraints = {
        @UniqueConstraint(columnNames = {"tid", "internalName"})
})
@NamedQueries({
        @NamedQuery(name = "TableColumn.findAllByDatabaseId", query = "select c from TableColumn c where c.table.database.id = ?1"),
})
public class TableColumn implements Comparable<TableColumn> {

    @Id
    @EqualsAndHashCode.Include
    @GeneratedValue(generator = "columns-sequence")
    @GenericGenerator(name = "columns-sequence", strategy = "increment")
    @Column(updatable = false, nullable = false)
    private Long id;

    @ToString.Exclude
    @OneToOne(fetch = FetchType.LAZY, cascade = {CascadeType.MERGE})
    @JoinColumn(name = "dfid", referencedColumnName = "id")
    private ContainerImageDate dateFormat;

    @ToString.Exclude
    @org.springframework.data.annotation.Transient
    @ManyToOne(fetch = FetchType.LAZY, cascade = {CascadeType.MERGE})
    @JoinColumns({
            @JoinColumn(name = "tID", referencedColumnName = "id", nullable = false)
    })
    private Table table;

    @ToString.Exclude
    @org.springframework.data.annotation.Transient
    @ManyToMany(fetch = FetchType.LAZY, cascade = CascadeType.MERGE, mappedBy = "columns")
    private List<View> views;

    @Column(name = "cname", nullable = false)
    private String name;

    @Column(name = "auto_generated", columnDefinition = "BOOLEAN default false")
    private Boolean autoGenerated;

    @Column(nullable = false)
    private String internalName;

    @Column(nullable = false, columnDefinition = "BOOLEAN default false")
    private Boolean isPrimaryKey;

    @Column
    private Long indexLength;

    @Column
    private String alias;

    @Column(name = "datatype", nullable = false, columnDefinition = "ENUM('CHAR','VARCHAR','BINARY','VARBINARY','TINYBLOB','TINYTEXT','TEXT','BLOB','MEDIUMTEXT','MEDIUMBLOB','LONGTEXT','LONGBLOB','ENUM','SET','BIT','TINYINT','BOOL','SMALLINT','MEDIUMINT','INT','BIGINT','FLOAT','DOUBLE','DECIMAL','DATE','DATETIME','TIMESTAMP','TIME','YEAR')")
    @Enumerated(EnumType.STRING)
    private TableColumnType columnType;

    @Column
    private Long length;

    @Column(nullable = false, columnDefinition = "BOOLEAN default true")
    private Boolean isNullAllowed;

    @Column(nullable = false)
    private Integer ordinalPosition;

    @CreatedDate
    @Column(nullable = false, updatable = false, columnDefinition = "TIMESTAMP default NOW()")
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd'T'HH:mm:ss.SSSXXX", timezone = "UTC")
    private Instant created;

    @ManyToOne(fetch = FetchType.LAZY, cascade = {CascadeType.MERGE, CascadeType.PERSIST})
    @JoinTable(name = "mdb_columns_concepts",
            joinColumns = @JoinColumn(name = "cid", referencedColumnName = "id", nullable = false),
            inverseJoinColumns = @JoinColumn(name = "id", referencedColumnName = "id"))
    private TableColumnConcept concept;

    @ManyToOne(fetch = FetchType.LAZY, cascade = {CascadeType.MERGE, CascadeType.PERSIST})
    @JoinTable(name = "mdb_columns_units",
            joinColumns = @JoinColumn(name = "cid", referencedColumnName = "id", nullable = false),
            inverseJoinColumns = @JoinColumn(name = "id", referencedColumnName = "id"))
    private TableColumnUnit unit;

    @ElementCollection(fetch = FetchType.LAZY, targetClass = String.class)
    @CollectionTable(name = "mdb_columns_enums", joinColumns = @JoinColumn(name = "column_id"))
    @Column(name = "value", nullable = false)
    @JoinColumn(name = "column_id")
    @OnDelete(action = OnDeleteAction.CASCADE)
    private List<String> enums;

    @ElementCollection(fetch = FetchType.LAZY, targetClass = String.class)
    @CollectionTable(name = "mdb_columns_sets", joinColumns = @JoinColumn(name = "column_id"))
    @Column(name = "value", nullable = false)
    @JoinColumn(name = "column_id")
    @OnDelete(action = OnDeleteAction.CASCADE)
    private List<String> sets;

    @Column
    private Long size;

    @Column
    private Long d;

    @Column(name = "val_min")
    private BigDecimal valMin;

    @Column(name = "val_max")
    private BigDecimal valMax;

    @Column
    private BigDecimal mean;

    @Column
    private BigDecimal median;

    @Column(name = "std_dev")
    private BigDecimal stdDev;

    @LastModifiedDate
    @Column(columnDefinition = "TIMESTAMP")
    private Instant lastModified;

    @Override
    public int compareTo(TableColumn tableColumn) {
        return Integer.compare(this.ordinalPosition, tableColumn.getOrdinalPosition());
    }

    /**
     * KEEP THIS FUNCTION HERE! IT WILL BREAK CODE!
     * Custom equality function implementation.
     *
     * @param object The other column.
     * @return True if columns are equal, false otherwise
     */
    public boolean equals(Object object) {
        if (object == null) {
            return false;
        }
        if (!(object instanceof final TableColumn other)) {
            return false;
        }
        return this.getId().equals(other.getId()) && this.getTable().equals(other.getTable());
    }
}
